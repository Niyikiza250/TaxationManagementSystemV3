    public void loadTable(){
        try {
            TaxPayerDao taxpayerdao = new TaxPayerDao();
            List<TaxPayer> taxpayer = taxpayerdao.getdataback();
            DefaultTableModel model = (DefaultTableModel)jTable1.getModel();
            model.setRowCount(0);
            for (TaxPayer taxPayer : taxpayer) {
                model.addRow(new Object[]{
                    taxPayer.getTin(),
                taxPayer.getFirstName(),
                taxPayer.getLastName(),
                taxPayer.getAmount(),
                taxPayer.getEmail(),
                taxPayer.getPhoneNumber()
                
                });
            }
        } catch (Exception e) {
        }
    }

