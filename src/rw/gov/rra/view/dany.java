    public  void Calculation(){
        double Assignment = Double.parseDouble(txtass.getText().trim());
        double mid = Double.parseDouble(txtmid.getText().trim());
        double finalmark = Double.parseDouble(txtfinalma.getText().trim());
        double attendance= Double.parseDouble(txtatt.getText().trim());
        
        double finalAvergae = ((Assignment*0.2)+(mid*0.3)+(finalmark*0.5));
        String finalavg= String.valueOf(finalAvergae);
        txtfinala.setText(finalavg);
        
        String grade; 
        String Schoola;
        if (finalAvergae>=80) {
            grade="A";
            txtgrade.setText(grade);
            
        }
        else if (finalAvergae<=79 && finalAvergae>=60) {
            grade ="B";
            txtgrade.setText(grade);}
       
        else if (finalAvergae<60) {
            grade ="C";
            txtgrade.setText(grade);
        }
        
        
    
    
    }
    
    public void Schoolacheck(){
        double Assignment = Double.parseDouble(txtass.getText().trim());
        double mid = Double.parseDouble(txtmid.getText().trim());
        double finalmark = Double.parseDouble(txtfinalma.getText().trim());
        double attendance= Double.parseDouble(txtatt.getText().trim());
        
        double finalAvergae = ((Assignment*0.2)+(mid*0.3)+(finalmark*0.5));
        
        
          if (finalAvergae>=75 && attendance>=80) {   
            txtsch.setText("Eligible for SchoolaShip");
        }
          else{
            txtsch.setText(" Not Eligible for Schoolaship");
            
        }
    }
    
    

