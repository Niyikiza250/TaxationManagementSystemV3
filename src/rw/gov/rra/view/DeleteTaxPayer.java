    private void btnToDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnToDeleteActionPerformed
            
        String idToDelete= txtIdSearch.getText().trim();
        
        TaxPayer taxDelete =new TaxPayer();
            taxDelete.setTin(idToDelete);
            TaxPayerDao taxDaoDelete = new TaxPayerDao();

              int answer;
        answer = JOptionPane.showConfirmDialog(null,"Are you sure for this delete? yes/no", "Confirmation Message",JOptionPane.YES_NO_OPTION,JOptionPane.WARNING_MESSAGE);
            
        if (answer==JOptionPane.YES_OPTION) {
              int rowsAffected= taxDaoDelete.DeleteTaxPayer(taxDelete);
            if (rowsAffected>0) {
                LandingPage form = new LandingPage();
                form.loadTable();
            ImageIcon doneIcon = new ImageIcon(getClass().getResource("well-done.png"));
        JOptionPane.showMessageDialog(this, " User Deleted Successfully","Deletion  Form",JOptionPane.INFORMATION_MESSAGE,doneIcon);
        
       form.setVisible(true);
       this.dispose();
        }
        }
          
        


        
    }//GEN-LAST:event_btnToDeleteActionPerformed

    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        String tinTosearch=txtIdSearch.getText().trim();
       
            TaxPayer tax =new TaxPayer();
        tax.setTin(tinTosearch);
        TaxPayerDao taxdao=new TaxPayerDao();
        TaxPayer taxback= taxdao.searchTaxPayer(tax);
        txttin.setText(taxback.getTin());
        txtFname.setText(taxback.getFirstName());
        txtLname.setText(taxback.getLastName());
        txtamount.setText(String.valueOf(taxback.getAmount()));
        txtEmail.setText(taxback.getEmail());
        txtPhone.setText(taxback.getPhoneNumber());
        txttin.setEditable(false);
    }//GEN-LAST:event_btnSearchActionPerformed

