    private void registerBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_registerBtnActionPerformed
        String username=txtUsername2.getText().trim();
        String password=txtPassword.getText().trim();
        
        LoginFormClass toLogin = new LoginFormClass(username, password);
        TaxPayerDao taxDao = new TaxPayerDao();
        
        taxDao.Authenticate(toLogin);
        if (username==toLogin.getUsername() && password==toLogin.getPassword()) {
            
            LandingPage form = new LandingPage();
        form.setVisible(true);
        this.dispose();
        }
        else{
             ImageIcon doneIcon = new ImageIcon(getClass().getResource("cross.png"));
        JOptionPane.showMessageDialog(this, " Sorry Wrong register ","Registration Form",JOptionPane.INFORMATION_MESSAGE,doneIcon);
        }
        
        
    }//GEN-LAST:event_registerBtnActionPerformed

