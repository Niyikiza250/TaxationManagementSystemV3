    private void btnRegisterTaxPayerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegisterTaxPayerActionPerformed
        
        TaxPayer taxP = new TaxPayer();
        taxP.setTin(txtTin.getText().trim());
        taxP.setFirstName(txtFirstName.getText().trim());
        taxP.setLastName(txtLastName.getText().trim());
        taxP.setAmount(Double.parseDouble(txtAmount.getText().trim()));
        taxP.setEmail(txtEmail.getText().trim());
        taxP.setPhoneNumber(txtPhooneNumber.getText().trim());
        TaxPayerDao taxDao = new TaxPayerDao();
        int rowsAffected = taxDao.registerTaxPayer(taxP);
        if (rowsAffected>0) {
            LandingPage form = new LandingPage();
            form.loadTable();
                    ImageIcon doneIcon = new ImageIcon(getClass().getResource("well-done.png"));
        JOptionPane.showMessageDialog(this, " User Registration Successfully","Registration Form",JOptionPane.INFORMATION_MESSAGE,doneIcon);
        
       form.setVisible(true);
       this.dispose();
       
        }
        
        
        

    }//GEN-LAST:event_btnRegisterTaxPayerActionPerformed

