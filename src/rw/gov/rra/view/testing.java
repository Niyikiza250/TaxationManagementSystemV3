    public void calculations(){
        double math = Double.parseDouble(txtMath.getText().trim());
        double physic= Double.parseDouble(txtPhyisic.getText().trim());
        double biology = Double.parseDouble(txtBiology.getText().trim());
        double multi= Double.parseDouble(txtMulti.getText().trim());
        
        double total = math+physic+biology+multi;
        double average = total/4;
        txtTotal.setEditable(false);
        txtAverage.setEditable(false);
        txtTotal.setText(String.format("%.2f", total));
        txtAverage.setText(String.format("%.2f", average));
        
    }

