    private void btnToRegisterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnToRegisterActionPerformed
        String firstname=txtfirstname.getText().trim();
        String lastname=txtlastname.getText().trim();
        String password = txtPassword.getText().trim();
        String username=txtUsername.getText().trim();
        
        User use = new User(firstname,lastname,username,password);
        TaxPayerDao userDao =new TaxPayerDao();
        int rowsAffected= userDao.registerUser(use);
        if (rowsAffected>0) {
             ImageIcon doneIcon = new ImageIcon(getClass().getResource("well-done.png"));
        JOptionPane.showMessageDialog(this, " User Registration Successfully","Registration Form",JOptionPane.INFORMATION_MESSAGE,doneIcon);
            PageToLogin form =new PageToLogin();
        form.setVisible(true);
        this.dispose();
        }
        else{
          ImageIcon doneIcon = new ImageIcon(getClass().getResource("cross.png"));
        JOptionPane.showMessageDialog(this, " Sorry Wrong register ","Registration Form",JOptionPane.INFORMATION_MESSAGE,doneIcon);
        PageToLogin form =new PageToLogin();
        form.setVisible(true);
        this.dispose();
        }
        
       
    }//GEN-LAST:event_btnToRegisterActionPerformed

