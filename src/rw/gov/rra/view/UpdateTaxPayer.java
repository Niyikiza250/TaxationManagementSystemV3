    private void btnToUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnToUpdateActionPerformed
        String tin =txttin.getText().trim();
        String fname=txtFname.getText().trim();
        String lname=txtLname.getText().trim();
        String amount=txtamount.getText().trim();
        String email=txtEmail.getText().trim();
        String phone=txtPhone.getText().trim();
        
        TaxPayer taxToUpdate = new TaxPayer(tin,fname,lname,Double.parseDouble(amount),email,phone);
  
        TaxPayerDao taxDao = new TaxPayerDao();
        int rowsAffected = taxDao.UpdateTaxPayer(taxToUpdate);
        if (rowsAffected>0) {
            LandingPage form = new LandingPage();
            form.loadTable();
            ImageIcon doneIcon = new ImageIcon(getClass().getResource("well-done.png"));
        JOptionPane.showMessageDialog(this, " User Updated Successfully","Update Form",JOptionPane.INFORMATION_MESSAGE,doneIcon);
        
       form.setVisible(true);
       this.dispose();
        }
        
        
    }//GEN-LAST:event_btnToUpdateActionPerformed

    private void btnToSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnToSearchActionPerformed
        String tinTosearch=txtIdSearch.getText().trim();
       
            TaxPayer tax =new TaxPayer();
        tax.setTin(tinTosearch);
        TaxPayerDao taxdao=new TaxPayerDao();
        TaxPayer taxback= taxdao.searchTaxPayer(tax);
        txttin.setText(taxback.getTin());
        txtFname.setText(taxback.getFirstName());
        txtLname.setText(taxback.getLastName());
        txtamount.setText(String.valueOf(taxback.getAmount()));
        txtEmail.setText(taxback.getEmail());
        txtPhone.setText(taxback.getPhoneNumber());
        txttin.setEditable(false);
        
        
        
        
        
        
    }//GEN-LAST:event_btnToSearchActionPerformed

